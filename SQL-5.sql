-- product sales summary

select * from `e1.order_items`
limit 4

select 
  ProductID,
  count(*) as total_order,
  sum(Total) as total,
  avg(total) as avg_total,
  max(Total) as max_sale,
  min(Total) as min_sale
from `e1.order_items`
group by ProductID

-- rounding off upto 3 decimal placess

select 
  ProductID,
  count(*) as total_order,
  sum(Total) as total,
  round(avg(total), 3) as avg_total,
  max(Total) as max_sale,
  min(Total) as min_sale
from `e1.order_items`
group by ProductID

